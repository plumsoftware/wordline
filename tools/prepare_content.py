def positions(word, row, col, down):
 return [(row + (i if down else 0), col + (0 if down else i)) for i in range(len(word))]

def place(words, placed=(), cells=None):
 cells = cells or {}
 if not words: return placed
 word = words[0]
 choices = [(0,0,False)] if not placed else []
 for (r,c), (letter,dirs) in sorted(cells.items()):
  for i,ch in enumerate(word):
   if ch == letter:
    for down in (False,True):
     if down not in dirs: choices.append((r-i if down else r, c if down else c-i, down))
 for r,c,down in choices:
  points=positions(word,r,c,down)
  before=(r-1,c) if down else (r,c-1)
  after=(r+len(word),c) if down else (r,c+len(word))
  if before in cells or after in cells: continue
  valid=True
  for p,ch in zip(points,word):
   if p in cells:
    if cells[p][0] != ch or down in cells[p][1]: valid=False;break
   else:
    a,b=p
    neighbors=[(a,b-1),(a,b+1)] if down else [(a-1,b),(a+1,b)]
    if any(n in cells for n in neighbors): valid=False;break
  if not valid: continue
  merged=dict(cells)
  for p,ch in zip(points,word): merged[p]=(ch, merged.get(p,('',set()))[1] | {down})
  rows=[p[0] for p in merged];cols=[p[1] for p in merged]
  if max(rows)-min(rows)>=9 or max(cols)-min(cols)>=9: continue
  result=place(words[1:], placed+((word,r,c,down),), merged)
  if result:return result
 return None

