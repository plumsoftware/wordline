"""Original synthesized game cues and a seamless quiet ambient loop; no sampled recordings."""
from pathlib import Path
import math
import struct
import wave
ROOT=Path(__file__).resolve().parents[1]/'app/src/main/res/raw'
ROOT.mkdir(parents=True,exist_ok=True)
RATE=22050

def write(name,samples):
 with wave.open(str(ROOT/(name+'.wav')),'wb') as out:
  out.setnchannels(1);out.setsampwidth(2);out.setframerate(RATE)
  out.writeframes(b''.join(struct.pack('<h',max(-32767,min(32767,int(x*32767)))) for x in samples))

def cue(name,notes):
 length=.14*len(notes)+.3
 data=[0.0]*int(RATE*length)
 for index,note in enumerate(notes):
  frequency=440*2**((note-69)/12)
  for i in range(int(.35*RATE)):
   t=i/RATE;start=int(index*.14*RATE)
   if start+i>=len(data):break
   data[start+i]+=.18*math.sin(2*math.pi*frequency*t)*(1-math.exp(-80*t))*math.exp(-12*t)
 write(name,data)
for name,notes in [('game_select',[72]),('game_success',[60,64,67]),('game_bonus',[67,72,76]),('game_reward',[60,64,67,72]),('game_neutral',[55])]:cue(name,notes)
# Frequencies complete an integer number of cycles in 16 seconds: sample boundaries are continuous.
seconds=16;tones=[(round((440*2**((note-69)/12))*seconds)/seconds,.035) for note in (48,55,60,64)]
write('game_ambient',[sum(amplitude*math.sin(2*math.pi*freq*i/RATE)*(0.8+0.2*math.cos(2*math.pi*i/(RATE*seconds))) for freq,amplitude in tones) for i in range(RATE*seconds)])
(ROOT/'audio_sources.txt').write_text('Original synthesized audio generated by tools/prepare_audio.py. No third-party samples. Project-owned composition.\n')
print('Prepared 5 cues and 16-second seamless ambient loop')
